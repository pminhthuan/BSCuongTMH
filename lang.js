/*==================================================
=          LANGUAGE SWITCHER (VI / EN)
==================================================*/

(function () {

    const STORAGE_KEY = "site-lang";

    function getSavedLang() {

        try {
            return localStorage.getItem(STORAGE_KEY);
        } catch (e) {
            return null;
        }

    }

    function saveLang(lang) {

        try {
            localStorage.setItem(STORAGE_KEY, lang);
        } catch (e) {
            /* ignore (private browsing, etc.) */
        }

    }

    function applyLanguage(lang) {

        document.documentElement.setAttribute("lang", lang);

        document.querySelectorAll("[data-i18n]").forEach(function (el) {

            const key = el.getAttribute("data-i18n");
            const entry = I18N[key];

            if (!entry || entry[lang] === undefined) return;

            const attr = el.getAttribute("data-i18n-attr");

            if (attr) {
                el.setAttribute(attr, entry[lang]);
            } else {
                el.innerHTML = entry[lang];
            }

        });

        document.querySelectorAll(".lang-toggle").forEach(function (btn) {

            btn.querySelectorAll("[data-lang-option]").forEach(function (opt) {

                opt.classList.toggle(
                    "active",
                    opt.getAttribute("data-lang-option") === lang
                );

            });

        });

        window.currentLang = lang;

        saveLang(lang);

    }

    function initLanguageSwitcher() {

        const saved = getSavedLang();
        const initial = (saved === "en" || saved === "vi") ? saved : "vi";

        applyLanguage(initial);

        document.querySelectorAll(".lang-toggle [data-lang-option]").forEach(function (opt) {

            opt.addEventListener("click", function () {

                const lang = this.getAttribute("data-lang-option");

                if (lang === window.currentLang) return;

                applyLanguage(lang);

            });

        });

    }

    if (document.readyState === "loading") {
        document.addEventListener("DOMContentLoaded", initLanguageSwitcher);
    } else {
        initLanguageSwitcher();
    }

    window.applyLanguage = applyLanguage;

})();
